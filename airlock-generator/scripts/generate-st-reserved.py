#!/usr/bin/env python3
"""Scalar ST generator for incident-group reservation. Offline draft, NOT Owen QA.

Unrolls a validated topology; no inferred vendor serialization or field mapping.
The restricted scalar ST syntax matches the existing two-door block.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / 'experimental/fixtures/real-cad-1252-1274-candidate.json'
BASE = ROOT / 'experimental/issue28/st-acceptance'


def topology(candidate):
    doors = candidate['physicalDoors']
    groups = candidate['interlockZones']
    ids = [d['id'] for d in doors]
    gids = [g['roomId'] for g in groups]
    if not ids or len(ids) != len(set(ids)) or not gids or len(gids) != len(set(gids)):
        raise ValueError('EMPTY_OR_DUPLICATE_TOPOLOGY')
    if any(not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', x) for x in ids + gids):
        raise ValueError('INVALID_ST_IDENTIFIER')
    if len({x.upper() for x in ids}) != len(ids) or len({x.upper() for x in gids}) != len(gids):
        raise ValueError('CASE_INSENSITIVE_ID_COLLISION')
    if any(d['a'] == d['b'] for d in doors):
        raise ValueError('SELF_DOOR')
    for g in groups:
        incident = [d['id'] for d in doors if g['roomId'] in (d['a'], d['b'])]
        if not incident or len(set(g['doorIds'])) != len(g['doorIds']) or set(g['doorIds']) != set(incident):
            raise ValueError('GROUP_MUST_MATCH_INCIDENT_DOORS')
        if g.get('timedBlockHoldSec') != 10:
            raise ValueError('ONLY_CONFIRMED_TEN_SECOND_HOLD')
    if any(not any(d['id'] in g['doorIds'] for g in groups) for d in doors):
        raise ValueError('DOOR_WITHOUT_CONTROLLED_GROUP')
    return ids, groups


def generate(candidate, name='FB_Airlock7'):
    ids, groups = topology(candidate)
    if not re.fullmatch(r'FB_[A-Za-z0-9_]+', name):
        raise ValueError('INVALID_BLOCK_NAME')
    incident = {d: [g for g in groups if d in g['doorIds']] for d in ids}
    neighbors = {d: [n for n in ids if n != d and any(n in g['doorIds'] for g in incident[d])] for d in ids}
    lines = ['// Generated by scripts/generate-st-reserved.py. TEST ONLY.',
             '// ST_NATIVE_NOT_VERIFIED; no terminal assignments; no retained state.',
             '// Priority is fixture physicalDoors order. No BUSY. No transitive blocking.',
             f'FUNCTION_BLOCK {name}', '', 'VAR_INPUT']
    def emit(s=''): lines.append(s)
    def both(xs): return ' AND '.join(xs) or 'TRUE'
    def either(xs): return ' OR '.join(xs) or 'FALSE'
    for d in ids:
        emit(f'  CLOSED_{d} : BOOL;')
        emit(f'  REQUEST_{d} : BOOL;')
    emit('  FIRE_NORMAL : BOOL;\n  RESET : BOOL;\n  DATA_HEALTHY : BOOL;\nEND_VAR\n\nVAR_OUTPUT')
    for d in ids:
        for prefix in ('PERMIT', 'GREEN', 'RESERVED', 'OVERTIME'):
            emit(f'  {prefix}_{d} : BOOL;')
        emit(f'  STATE_{d} : UDINT;')
    for g in groups: emit(f"  READY_{g['roomId']} : BOOL;")
    emit('  BUZZER : BOOL;\n  FAULT : BOOL;\n  EMERGENCY : BOOL;\nEND_VAR\n\nVAR')
    emit('  FaultLatch : BOOL := FALSE;\n  RecoveryLatch : BOOL := FALSE;')
    emit('  PreviousReset : BOOL := TRUE;\n  FreshReset : BOOL;\n  Normal : BOOL;')
    emit('  AllClosed : BOOL;\n  RequestsLow : BOOL;\n  InvalidState : BOOL;\n  RecoveryAccepted : BOOL;')
    for d in ids:
        emit(f'  S_{d} : UDINT := 0;')
        emit(f'  Previous_{d} : BOOL := TRUE;')
        for p in ('Fresh', 'OldBusy', 'Eligible'): emit(f'  {p}_{d} : BOOL;')
        for p in ('Window', 'Open'): emit(f'  {p}_{d} : SYS.TON;')
    for g in groups:
        emit(f"  Closed_{g['roomId']} : BOOL;")
        emit(f"  Hold_{g['roomId']} : SYS.TON;")
    emit('END_VAR\n')
    emit('FreshReset := RESET AND NOT PreviousReset;')
    emit(f"AllClosed := {both(['CLOSED_'+d for d in ids])};")
    emit(f"RequestsLow := {both(['NOT REQUEST_'+d for d in ids])};")
    emit('RecoveryAccepted := FALSE;')
    emit('InvalidState := ' + either([f'((S_{d} <> 0) AND (S_{d} <> 20) AND (S_{d} <> 21))' for d in ids]) + ';')
    emit('IF InvalidState THEN FaultLatch := TRUE; END_IF;')
    for d in ids:
        emit(f'Fresh_{d} := REQUEST_{d} AND NOT Previous_{d};')
        emit(f'OldBusy_{d} := S_{d} <> 0;')
    for g in groups:
        members = g['doorIds']
        emit(f"Closed_{g['roomId']} := {both(['CLOSED_'+d for d in members])};")
        for i, a in enumerate(members):
            for b in members[i+1:]:
                emit(f'IF NOT CLOSED_{a} AND NOT CLOSED_{b} THEN FaultLatch := TRUE; END_IF;')
    emit('IF NOT FIRE_NORMAL OR NOT DATA_HEALTHY THEN RecoveryLatch := TRUE; END_IF;')
    emit('IF (FaultLatch OR RecoveryLatch) AND NOT InvalidState AND FreshReset AND')
    emit('   FIRE_NORMAL AND DATA_HEALTHY AND AllClosed AND RequestsLow THEN')
    emit('  FaultLatch := FALSE;\n  RecoveryLatch := FALSE;\n  RecoveryAccepted := TRUE;\nEND_IF;')
    emit('Normal := FIRE_NORMAL AND DATA_HEALTHY AND NOT FaultLatch AND NOT RecoveryLatch;')
    for g in groups:
        r = g['roomId']
        emit(f'Hold_{r}(I := Closed_{r} AND Normal AND NOT RecoveryAccepted, T := T#10s);')
    # Eligibility captures pre-transition busy. Cancel/close never admits a
    # competing edge in the same scan, matching the two-door contract.
    for d in ids:
        guards = [f'Fresh_{d}', f'S_{d} = 0', 'Normal', 'NOT RecoveryAccepted']
        guards += [f'Hold_{g["roomId"]}.Q' for g in incident[d]]
        guards += [f'NOT OldBusy_{n}' for n in neighbors[d]]
        emit(f"Eligible_{d} := {both(['('+x+')' for x in guards])};")
    for d in ids:
        closed = both([f'Closed_{g["roomId"]}' for g in incident[d]])
        emit(f'IF NOT Normal OR RecoveryAccepted THEN S_{d} := 0;')
        emit('ELSE')
        emit(f'  CASE S_{d} OF\n    0: S_{d} := 0;\n    20:')
        emit(f'      IF NOT CLOSED_{d} THEN S_{d} := 21;')
        emit(f'      ELSIF NOT ({closed}) THEN S_{d} := 0;')
        emit(f'      ELSIF NOT REQUEST_{d} OR Window_{d}.Q THEN S_{d} := 0;\n      END_IF;')
        emit(f'    21: IF CLOSED_{d} THEN S_{d} := 0; END_IF;')
        emit(f'    ELSE S_{d} := 0;\n  END_CASE;\nEND_IF;')
    emit('// Ordered allocation observes earlier accepted reservations this scan.')
    for d in ids:
        guards = [f'Eligible_{d}'] + [f'(S_{n} = 0)' for n in neighbors[d]]
        emit(f"IF {both(guards)} THEN S_{d} := 20; END_IF;")
    for d in ids:
        closed = both([f'Closed_{g["roomId"]}' for g in incident[d]])
        emit(f'Window_{d}(I := (S_{d} = 20) AND ({closed}) AND Normal, T := T#5s);')
        emit(f'Open_{d}(I := NOT CLOSED_{d}, T := T#30s);')
    emit('FAULT := FaultLatch OR RecoveryLatch;\nEMERGENCY := NOT FIRE_NORMAL;')
    for d in ids:
        guards = ['Normal', 'NOT FAULT', f'S_{d} = 20', f'REQUEST_{d}', f'NOT Window_{d}.Q']
        guards += [f'Hold_{g["roomId"]}.Q' for g in incident[d]]
        guards += [f'Closed_{g["roomId"]}' for g in incident[d]]
        emit(f"PERMIT_{d} := {both(['('+x+')' for x in guards])};")
        emit(f'GREEN_{d} := PERMIT_{d};')
        emit(f'RESERVED_{d} := Normal AND ((S_{d} = 20) OR (S_{d} = 21));')
        emit(f'OVERTIME_{d} := Open_{d}.Q;\nSTATE_{d} := S_{d};')
    for g in groups:
        r = g['roomId']
        emit(f'READY_{r} := Normal AND NOT FAULT AND Hold_{r}.Q;')
    emit('BUZZER := FAULT OR ' + either([f'OVERTIME_{d}' for d in ids]) + ';')
    for d in ids: emit(f'Previous_{d} := REQUEST_{d};')
    emit('PreviousReset := RESET;\n\nEND_FUNCTION_BLOCK')
    return '\n'.join(lines) + '\n'


